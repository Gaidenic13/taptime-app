let currentLang = localStorage.getItem("taptime_lang") || "en";
export const getLang = () => currentLang;
export const dateLocale = () => (currentLang === "ro" ? "ro-RO" : "en-GB");

const I18nCtx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(currentLang);
  const setLang = (l) => {
    currentLang = l;
    localStorage.setItem("taptime_lang", l);
    setLangState(l);
  };
  const t = (key, vars) => {
    let str = dict[lang][key] ?? dict.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
    return str;
  };
  return <I18nCtx.Provider value={{ t, lang, setLang }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);

export function LangSwitch({ compact }) {
  const { lang, setLang } = useI18n();
  return (
    <div className={`lang-switch ${compact ? "compact" : ""}`} role="group" aria-label="Language">
      {["en", "ro"].map((l) => (
        <button key={l} type="button" className={lang === l ? "active" : ""} onClick={() => setLang(l)}>
          {l.toUpperCase()}
        </button>
      ))}
    </div>
  );
}
